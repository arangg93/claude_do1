def main():
    if len(sys.argv) < 2:
        print("사용법: python3 check.py <본문파일>"); return 1
    text = open(sys.argv[1], encoding='utf-8').read()
    problems = []

    for bad, good in BAD.items():
        for m in re.finditer(re.escape(bad), text):
            line = text[:m.start()].count('\n') + 1
            problems.append(f"{line}행: '{bad}' -> '{good}'")

    if '�' in text:
        problems.append("깨진 문자(U+FFFD)가 있습니다")
    if re.search(r'[㄰-㆏]', text):
        problems.append("홀로 떨어진 한글 자모가 있습니다")
    for m in re.finditer(r'</[a-z]*[0-9a-f]{4}>', text):
        problems.append(f"잘못된 HTML 닫는 태그: {m.group()}")

    n_items = len(re.findall(r'>\s*\d+\.\s', text))
    n_links = len(re.findall(r'https?://', text))
    print(f"항목 {n_items}개 / 주소 {n_links}개")
    if n_items and n_links < n_items:
        problems.append(f"주소가 항목보다 적습니다 (항목 {n_items}, 주소 {n_links})")

    if problems:
        print("\n고칠 것 %d개" % len(problems))
        for p in problems: print("  -", p)
        return 1
    print("통과. 고칠 것이 없습니다.")
    return 0

sys.exit(main())
